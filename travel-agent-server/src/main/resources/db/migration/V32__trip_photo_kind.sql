-- V32：照片通道支持「发票」用途（trip_photo.kind）
--
-- 背景：批次 3 的发票报销复用现有照片通道，不新建存储、不新建发票实体/表：
-- 用户把发票照片当普通照片上传，kind=INVOICE 标记用途；报销流程取该用户最新一张识别。
--
-- 为什么加列而不是新表：发票图片的字节、配额（单行程张数 / 单用户容量）、归属与
-- 级联删除都与照片完全一致，唯一多出来的信息是「这张图是发票」；新表只会把文件
-- 存储与配额逻辑再复制一遍，还要额外维护两套清理路径。
--
-- kind 默认 PHOTO：存量行全部是普通照片，迁移即回填，读写两侧都不用猜。
-- 没有库级枚举约束：取值由 PhotoService 校验（PHOTO / INVOICE），与库内其他
-- 状态列（expense.category、operation_history.domain）口径一致。
--
-- 方言：H2(MODE=MySQL) 与 MySQL 8.0 共用同一份脚本（与 V30 / V31 同一写法）；
-- 不加 IF NOT EXISTS（MySQL 8.0 的 ALTER ADD COLUMN 不支持），Flyway 保证每库只跑一次。
-- ============================================================================

ALTER TABLE trip_photo ADD COLUMN kind VARCHAR(20) DEFAULT 'PHOTO';